const getInitialLang = () => {
    let savedLang = localStorage.getItem('fyzen_lang');
    if (!savedLang) {
        const browserLang = navigator.language || navigator.userLanguage || 'ru';
        if (browserLang.startsWith('uz')) savedLang = 'uz';
        else if (browserLang.startsWith('en')) savedLang = 'en';
        else savedLang = 'ru';
        localStorage.setItem('fyzen_lang', savedLang);
    }
    return savedLang;
};
