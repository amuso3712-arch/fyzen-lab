function getCurrentLang() {
    return localStorage.getItem('fyzen_lang') || 'ru';
}

function t(key) {
    if (!key) return '';
    const lang = getCurrentLang();
    const k = key.toLowerCase();
    // Search for the key in a case-insensitive way
    const foundKey = Object.keys(translations[lang]).find(keyName => keyName.toLowerCase() === k);
    return foundKey ? translations[lang][foundKey] : key;
}

function changeLanguage(lang) {
    if (!translations[lang]) return;
    localStorage.setItem('fyzen_lang', lang);
    updateTexts(); 
    
    // Smoothly re-render dynamic products if on the products page
    if (typeof renderDynamicProducts === 'function') {
        renderDynamicProducts();
    }
    if (typeof refreshProductDetailLanguage === 'function') {
        refreshProductDetailLanguage();
    }

    if(typeof showToast === 'function') {
        const msg = translations[lang].lang_changed || "Language changed";
        showToast(msg, 'success');
    }
}

function updateTexts() {
    const lang = getCurrentLang();
    if (!translations[lang]) return;
    document.documentElement.lang = lang;

    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (!key) return;
        
        const translatedText = t(key);
        // Even if translatedText === key, we might want to update it 
        // to reset any previous translations if the key itself is meaningful
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            el.placeholder = translatedText;
        } else {
            el.innerHTML = translatedText;
        }
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria-label');
        if (key) el.setAttribute('aria-label', t(key));
    });

    const searchInput = document.getElementById('searchInput');
    if (searchInput) {
        searchInput.placeholder = t('search_placeholder');
    }

    // Update active class on language buttons
    document.querySelectorAll('.nav-lang-switcher button, .lang-switcher button, .lang-btn, .dyn-lang-right button').forEach(btn => {
        const btnLang = btn.getAttribute('data-lang') || 
                       (btn.getAttribute('onclick') ? btn.getAttribute('onclick').match(/'([^']+)'/)?.[1] : null);
        
        if (btnLang === lang) {
            btn.classList.add('active');
            btn.classList.add('active-lang');
        } else {
            btn.classList.remove('active');
            btn.classList.remove('active-lang');
        }
    });

    document.body.classList.add('lang-ready');
}

// Alias for convenience and backward compatibility
const updateI18n = updateTexts;

// Run immediately if DOM is already ready
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', updateTexts);
} else {
    updateTexts();
}

// Use one delegated capture handler for every language control. This keeps mobile
// drawer taps reliable even when the drawer is layered above other controls.
document.addEventListener('click', (event) => {
    const source = event.target;
    const button = source instanceof Element ? source.closest('.lang-btn') : null;
    if (!button) return;

    const lang = button.dataset.lang || button.getAttribute('onclick')?.match(/[\"']([^\"']+)[\"']/)?.[1];
    if (!lang || !translations[lang]) return;

    event.preventDefault();
    event.stopPropagation();
    changeLanguage(lang);
}, true);

window.getI18nText = t; // Global access for other scripts
window.updateI18n = updateTexts;
window.changeLanguage = changeLanguage;
